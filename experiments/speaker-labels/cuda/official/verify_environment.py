"""Reject changes to parent package versions, source files, and binary payloads."""
import hashlib
import importlib.metadata
import json
from pathlib import Path
import sys


def sha256(path):
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(4 * 1024**2), b""):
            digest.update(block)
    return digest.hexdigest()


def snapshot():
    packages, payload = {}, {}
    for distribution in importlib.metadata.distributions():
        name = distribution.metadata["Name"].lower().replace("_", "-")
        packages[name] = distribution.version
        if distribution.files is None:
            raise ValueError(f"Parent package has no file inventory: {name}")
        for entry in distribution.files:
            # Installer records and generated bytecode may change without changing payloads.
            if (entry.suffix in (".pyc", ".pyo") or "__pycache__" in entry.parts
                    or any(part.endswith((".dist-info", ".egg-info")) for part in entry.parts)):
                continue
            path = Path(distribution.locate_file(entry)).absolute()
            key = str(path)
            if key not in payload:
                payload[key] = sha256(path)
    return {"packages": packages, "payload": payload}


def verify(old, current):
    for name, version in old["packages"].items():
        if current["packages"].get(name) != version:
            raise ValueError(f"Parent package changed: {name}")
    for path, digest in old["payload"].items():
        if current["payload"].get(path) != digest:
            raise ValueError(f"Parent package payload changed: {path}")
    return {"parent_packages_unchanged": len(old["packages"]),
            "parent_payload_files_unchanged": len(old["payload"]),
            "added_packages": {k: v for k, v in current["packages"].items() if k not in old["packages"]}}


def main():
    path = Path("/opt/frontend-parent.json")
    current = snapshot()
    if sys.argv[1] == "save":
        path.write_text(json.dumps(current, sort_keys=True))
    elif sys.argv[1] == "verify":
        print(json.dumps(verify(json.loads(path.read_text()), current), sort_keys=True))
    else:
        raise ValueError("Expected save or verify")


if __name__ == "__main__":
    main()
